    //--------------------- Métodos auxiliares ---------------------
    private void nuevaLiquidacion() {
        lineasTemp.clear();
        txtNumero.setText(String.format("LIQ-%04d", almacen.siguienteConsecutivo()));
        txtIdentificacion.setText("");
        dchInicial.setDate(null);
        dchFinal.setDate(null);
        txtJustificacion.setText("");
        limpiarLinea();
        refrescarLineas();
    }

    private void limpiarLinea() {
        cmbTipo.setSelectedIndex(0);
        txtMonto.setText("");
    }

    private void refrescarLineas() {
        DefaultTableModel modelo = (DefaultTableModel) tblLineas.getModel();
        modelo.setRowCount(0);
        double total = 0;
        for (ObjDetalleViatico l : lineasTemp) {
            modelo.addRow(new Object[]{l.getTipoViatico(), l.getMonto()});
            total += l.getMonto();
        }
        lblTotal.setText(String.format("%,.2f", total));
    }

    private void refrescarLiquidaciones() {
        DefaultTableModel modelo = (DefaultTableModel) tblLiquidaciones.getModel();
        modelo.setRowCount(0);
        for (ObjLiquidacion liq : almacen.listar()) {
            modelo.addRow(new Object[]{liq.getNumero(), liq.getIdentificacion(),
                formato.format(liq.getFechaInicial()), formato.format(liq.getFechaFinal()),
                liq.getJustificacion(), String.format("%,.2f", liq.getTotal())});
        }
        mostrarDetalle();
    }

    //--Muestra las líneas de la liquidación seleccionada en la pestaña Consultar
    private void mostrarDetalle() {
        DefaultTableModel modelo = (DefaultTableModel) tblDetalleConsulta.getModel();
        modelo.setRowCount(0);
        int fila = tblLiquidaciones.getSelectedRow(); //--Posición en la lista (-1 = nada seleccionado)
        ArrayList<ObjLiquidacion> lista = almacen.listar();
        if (fila == -1 || fila >= lista.size()) {
            lblDetalle.setText("Detalle de la liquidación seleccionada");
            return;
        }
        ObjLiquidacion liq = lista.get(fila); //--fila -> objeto
        lblDetalle.setText("Detalle de " + liq.getNumero() + " - " + liq.getJustificacion());
        for (ObjDetalleViatico l : liq.getDetalle()) {
            modelo.addRow(new Object[]{l.getTipoViatico(), String.format("%,.2f", l.getMonto())});
        }
    }

    private void aviso(String mensaje) {
        JOptionPane.showMessageDialog(null, mensaje, "Aviso Importante", JOptionPane.WARNING_MESSAGE);
    }

