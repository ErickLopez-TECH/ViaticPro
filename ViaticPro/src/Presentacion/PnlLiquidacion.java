    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String tipo = (String) cmbTipo.getSelectedItem();
        String montoTxt = txtMonto.getText().trim().replace(",", ".");
        String error = misMetodos.validarLinea(tipo, montoTxt);
        if (error != null) {
            aviso(error);
            return;
        }
        lineasTemp.add(new ObjDetalleViatico(tipo,
                Double.parseDouble(montoTxt)));
        refrescarLineas();
        limpiarLinea();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int fila = tblLineas.getSelectedRow();
        if (fila == -1) { //--Nada seleccionado
            aviso("Seleccione la línea que desea quitar");
            return;
        }
        lineasTemp.remove(fila);
        refrescarLineas();
    }//GEN-LAST:event_btnQuitarActionPerformed

