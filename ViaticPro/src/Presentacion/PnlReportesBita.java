    private void btnFiltroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltroActionPerformed

        if(!validarCampos()){
            return;
        }
        String usuario = "";
        if (cmbNombre.getSelectedItem() != null) {
            usuario = cmbNombre.getSelectedItem().toString().trim();
        }

        
        String fechaInicio = "";
        if (dtcFechIn.getDate() != null) {
            SimpleDateFormat sdfFormato = new java.text.SimpleDateFormat("yyyy-MM-dd");
            fechaInicio = sdfFormato.format(dtcFechIn.getDate());
        }

        
        String fechaFin = "";
        if (dtcFechEnd.getDate() != null) {
            SimpleDateFormat sdfFormato = new java.text.SimpleDateFormat("yyyy-MM-dd");
            fechaFin = sdfFormato.format(dtcFechEnd.getDate());
        }

        
        DefaultTableModel modeloFiltrado = almacenBitacora.filtrarBitacora(usuario, fechaInicio, fechaFin);
        tblViaticos.setModel(modeloFiltrado);
        
    }//GEN-LAST:event_btnFiltroActionPerformed

    
    private boolean validarCampos(){
        
        if(cmbNombre.getSelectedIndex() == 0){
            JOptionPane.showMessageDialog(this, "Seleccione un usuario en este campo", "Informacion",JOptionPane.INFORMATION_MESSAGE);
            cmbNombre.requestFocus();
            return false;
        }
        
        if(dtcFechIn.getDate() == null){
            JOptionPane.showMessageDialog(this, "Ingrese una fecha de inicio para aplicar el filtro", "Informacion",JOptionPane.INFORMATION_MESSAGE);
            dtcFechIn.getDateEditor().getUiComponent().requestFocusInWindow();
            return false;
        }
        
        if(dtcFechEnd.getDate() == null){
            JOptionPane.showMessageDialog(this, "Ingrese una fecha final para aplicar el filtro", "Informacion",JOptionPane.INFORMATION_MESSAGE);
            dtcFechEnd.getDateEditor().getUiComponent().requestFocusInWindow();
            return false;
        }
        
        return true;
    }
    
