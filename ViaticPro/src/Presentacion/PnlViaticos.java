    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
        int id = 0;
        
        //si no hay nada en ese txt es porque es nuevo registro
        if(txtId.getText().equals("")){
            //desde el metodos de logica
            id = viaticosMetodos.siguienteViatico();
            
        }else{
            id = Integer.parseInt(txtId.getText());
        }
        
        String nombre = txtNombre.getText();
        
        //validar si es numero
        double monto =0;
        try {
            monto = Double.parseDouble(txtMonto.getText());
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
        "Por favor, ingresa un número entero válido o decimal (sin letras).", 
        "Error de formato", 
        javax.swing.JOptionPane.ERROR_MESSAGE);
            txtMonto.requestFocus();
          return;
        }
        
        
        int estado = cmbEstado.getSelectedIndex();
        
        ObjViatico miViatico = new ObjViatico(id, nombre, monto, estado);
        
        
        //le dice que si el indice es = -1 esto quiere decir que debeb de garega pero de lo contarrio e sporque existe
        int indice = viaticosMetodos.buscarviatico(id);
        
        if(indice ==-1){
            
            //validacion de campoos antes d eguardar
            if(!validarCampos()){
                return;
            }
            
            miViatico.setId(viaticosMetodos.siguienteViatico());
            almacen.agregarViatico(miViatico);
            
            
            movimiento = "Agrego";
            
            
        }else{
            
            movimiento = "Edito";
            
            almacen.editarViatico(indice, miViatico);
        }
        
        
        int idBitacora = metodosBita.siguienteBitacora();
        
        ObjBitacora miBitacora = new ObjBitacora(idBitacora, nombreUser, seccion, movimiento);
        almacenBitacora.agregarBitacora(miBitacora);
        
        
        tblViaticos.setModel(almacen.mostrarViaticos());
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
       if(!txtId.getText().equals("")){
            int id = Integer.parseInt(txtId.getText());
            int indice = viaticosMetodos.buscarviatico(id);
            
            //ya tengo los datos
            ObjViatico miViatico= almacen.listarViaticos().get(indice);
            
            txtNombre.setText(miViatico.getNombre());
            txtMonto.setText(String.valueOf(miViatico.getMonto()));
            
            
            cmbEstado.setSelectedIndex(miViatico.getEstado());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private boolean validarCampos(){
        
        if(txtNombre.getText().equals("")){
            JOptionPane.showMessageDialog(this, "El Campo de nombre no puede estar vacio","Alerta",JOptionPane.INFORMATION_MESSAGE);
            txtNombre.requestFocus();
            return false;
        }
        return true;
    }
    
    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        
         if(!txtId.getText().equals("")){
            int id = Integer.parseInt(txtId.getText());
            int indice = viaticosMetodos.buscarviatico(id);
            
            if(indice != -1){
                almacen.eliminarViatico(indice);
                tblViaticos.setModel(almacen.mostrarViaticos());
                
                movimiento = "Elimino";
                int idBitacora = metodosBita.siguienteBitacora();
                ObjBitacora miBitacora = new ObjBitacora(idBitacora, nombreUser, seccion, movimiento);
                almacenBitacora.agregarBitacora(miBitacora);
                tblViaticos.setModel(almacen.mostrarViaticos());
            }
        }
  
    }//GEN-LAST:event_btnBorrarActionPerformed

